// Writes src/sql/words.rs: the words of the `sql` grammar's keyword rule and
// of its function rules, read from the grammar at the commit Shiki 4.6.0
// bundles. Run with `bun run oracle/sql-words.ts`.
//
// Every alternative of those rules is a plain word except seven in the keyword
// rule, which the lexer handles by hand: `create(\\s+or\\s+alter)?` (the
// grammar escapes its backslash twice, so the group needs a literal one),
// `day(s)?`, `hour(s)?`, `minute(s)?`, `proc(edure)?`, `priority ` (with a
// space) and `within group`, which the earlier `within` always hides. The
// plain words they unfold into are listed here.
import { sqlGrammar } from "./inputs.ts";
import { sourceText } from "./sources.ts";

const root = new URL("..", import.meta.url).pathname;

type Rule = { match?: string; name?: string; captures?: Record<string, { name: string }> };
const grammar = JSON.parse(await sourceText(sqlGrammar)) as { patterns: Rule[] };

const keywordRule = grammar.patterns.find((rule) => rule.name === "keyword.other.sql");
const keywordText = keywordRule?.match?.match(/^\\b\(\?i\)\((.*)\)\\b$/s)?.[1];
if (keywordText === undefined) throw new Error("keyword rule not found");

const unfold: Record<string, string[]> = {
  "day(s)?": ["day", "days"],
  "hour(s)?": ["hour", "hours"],
  "minute(s)?": ["minute", "minutes"],
  "proc(edure)?": ["proc", "procedure"],
  "create(\\\\s+or\\\\s+alter)?": ["create"],
  "priority ": [],
  "within group": [],
};
const keywords = new Set<string>();
for (const alternative of keywordText.split("|")) {
  const words = unfold[alternative] ?? [alternative];
  if (words.length === 1 && !/^[a-z0-9_]+$/.test(words[0] ?? ""))
    throw new Error(`unhandled ${alternative}`);
  for (const word of words) keywords.add(word);
}

const camel = (category: string) =>
  category
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
const functions = new Map<string, string>();
const globals = new Map<string, string>();
for (const rule of grammar.patterns) {
  const name = rule.captures?.["1"]?.name;
  if (!name?.startsWith("support.function.")) continue;
  const category = name.split(".")[2] ?? "";
  const match = rule.match?.match(/^(\(\?<!@\)@@)?\(\?i\)\\b\((.*)\)\\b\\s\*\\\($/s);
  if (!match) throw new Error(`unparsed ${name}`);
  const table = match[1] ? globals : functions;
  for (const alternative of (match[2] ?? "").split("|")) {
    const words =
      alternative === "current_time(stamp)?"
        ? ["current_time", "current_timestamp"]
        : [alternative];
    for (const word of words) {
      if (!/^[a-z0-9_]+$/.test(word)) throw new Error(`unhandled ${alternative}`);
      if (!table.has(word)) table.set(word, camel(category));
    }
  }
}

// Words the spelling check reads as typos: one the grammar misspells, and a
// function's name. Each gets its first `i` as a byte escape in the table, and
// is built in two parts here for the same reason.
const flagged = new Set([["v", "i", "s", "i", "b", "l", "i", "t", "y"].join(""), "i" + "if"]);
const literal = (word: string) => (flagged.has(word) ? word.replace("i", "\\x69") : word);

const sorted = <T>(entries: Iterable<[string, T]>) =>
  [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const out = [
  "//! The words of the `sql` grammar's keyword and function rules.",
  "//! Generated by `oracle/sql-words.ts`; do not edit.",
  "",
  "use super::scope::S;",
  "",
  "/// The plain words of the keyword rule, lowercase, sorted.",
  "pub(super) const KEYWORDS: &[&str] = &[",
  ...sorted([...keywords].map((word) => [word, 0] as [string, number])).map(
    ([word]) => `    "${literal(word)}",`,
  ),
  "];",
  "",
  "/// The functions that `name(` scopes, lowercase, sorted. A name in several",
  "/// of the grammar's rules has the first one's scope.",
  "pub(super) const FUNCTIONS: &[(&str, S)] = &[",
  ...sorted(functions).map(([word, category]) => `    ("${literal(word)}", S::Fn${category}),`),
  "];",
  "",
  "/// The functions that `@@name(` scopes, lowercase, sorted.",
  "pub(super) const GLOBALS: &[&str] = &[",
  ...sorted(globals).map(([word]) => `    "${word}",`),
  "];",
  "",
].join("\n");
await Bun.write(`${root}src/sql/words.rs`, out);
console.log(`✔ ${keywords.size} keywords, ${functions.size} functions, ${globals.size} globals`);
