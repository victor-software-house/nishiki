// Writes src/python/classes.rs: the characters that Oniguruma's `\w`, `\s`,
// `\d`, `[[:alpha:]]` and `\p{upper}` match beyond ASCII, as Shiki 4.6.0 uses
// them in the `python` grammar. Rust's `char` methods differ from them (`\w`
// includes marks, `\d` is only the decimal digits), so the tables are measured
// rather than derived: one line per character, tokenized by the grammar, and
// read back from its scopes.
//
//   `True<X>`        X is a word character when `True` is not a constant;
//   `@<X>`           X starts a name when a decorator opens (`[_[:alpha:]]`);
//   `@<X>x`          X is white space or starts a name when one opens;
//   `<X><X>`         X is a capital when the pair is a constant name;
//   `x = "{:>#<X><X>}"`  X is a digit when the placeholder is a format.
import { createHighlighter } from "shiki@4.6.0";

const root = new URL("..", import.meta.url).pathname;
const highlighter = await createHighlighter({ langs: ["python"], themes: ["github-dark"] });

/** The code points that can be letters, marks, digits or spaces: U+0080 to
 * the end of plane 3, and the variation selectors of plane 14. */
const points: number[] = [];
for (let cp = 0x80; cp < 0x34000; cp++) {
  if (cp < 0xd800 || cp > 0xdfff) points.push(cp);
}
for (let cp = 0xe0000; cp < 0xe0200; cp++) points.push(cp);

/** For each point, the tokens of its line: text and scope names. */
function probeParts(make: (ch: string) => string): { content: string; scopes: string[] }[][] {
  const text = points.map((cp) => make(String.fromCodePoint(cp))).join("\n");
  const lines = highlighter.codeToTokens(text, {
    lang: "python",
    theme: "github-dark",
    includeExplanation: "scopeName",
    tokenizeMaxLineLength: 0,
    tokenizeTimeLimit: 0,
  }).tokens;
  return lines.map((tokens) =>
    tokens.flatMap((token) =>
      (token.explanation ?? []).map((part) => ({
        content: part.content,
        scopes: part.scopes.map((s) => s.scopeName),
      })),
    ),
  );
}

/** For each point, the scope names of its line's tokens. */
function probe(make: (ch: string) => string): string[][] {
  return probeParts(make).map((parts) => parts.flatMap((part) => part.scopes));
}

const words = probe((ch) => `True${ch}`).map((scopes) => !scopes.includes("constant.language.python"));
const starts = probe((ch) => `@${ch}`).map((scopes) => scopes.includes("meta.function.decorator.python"));
const startsOrSpace = probe((ch) => `@${ch}x`).map((scopes) => scopes.includes("meta.function.decorator.python"));
const spaces = startsOrSpace.map((yes, i) => yes && !starts[i]);
const uppers = probe((ch) => `${ch}${ch}`).map((scopes) => scopes.includes("constant.other.caps.python"));
// Both brace-format patterns match any text after a colon; only the first
// scopes the whole spec as one token.
const digits = probeParts((ch) => `x = "{:>#${ch}${ch}}"`).map((parts) =>
  parts.some((part) => part.content.length > 1 && part.scopes.includes("storage.type.format.python")),
);

function ranges(flags: boolean[]): [number, number][] {
  const out: [number, number][] = [];
  flags.forEach((on, i) => {
    if (!on) return;
    const cp = points[i]!;
    const last = out[out.length - 1];
    if (last && last[1] + 1 === cp) last[1] = cp;
    else out.push([cp, cp]);
  });
  return out;
}

function table(name: string, doc: string, flags: boolean[]): string {
  const rows = ranges(flags)
    .map(([lo, hi]) => `    (0x${lo.toString(16)}, 0x${hi.toString(16)}),`)
    .join("\n");
  return `/// ${doc}\nconst ${name}: &[(u32, u32)] = &[\n${rows}\n];\n`;
}

const out = `//! The characters Oniguruma's \`\\w\`, \`\\s\`, \`\\d\`, \`[[:alpha:]]\` and \`\\p{upper}\` match
//! beyond ASCII, as Shiki 4.6.0 reads them. Generated by
//! \`oracle/python-classes.ts\`; do not edit.

${table("WORDS", "The non-ASCII characters `\\w` matches.", words)}
${table("ALPHAS", "The non-ASCII characters `[[:alpha:]]` matches.", starts)}
${table("SPACES", "The non-ASCII characters `\\s` matches.", spaces)}
${table("UPPERS", "The non-ASCII characters `\\p{upper}` matches.", uppers)}
${table("DIGITS", "The non-ASCII characters `\\d` matches.", digits)}
/// Whether \`c\` is in the sorted \`table\` of inclusive ranges.
fn contains(table: &[(u32, u32)], c: char) -> bool {
    let c = u32::from(c);
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// The regex \`\\w\` for a non-ASCII character.
pub(super) fn is_word(c: char) -> bool {
    contains(WORDS, c)
}

/// The regex \`[[:alpha:]]\` for a non-ASCII character.
pub(super) fn is_alpha(c: char) -> bool {
    contains(ALPHAS, c)
}

/// The regex \`\\s\` for a non-ASCII character.
pub(super) fn is_space(c: char) -> bool {
    contains(SPACES, c)
}

/// The regex \`\\p{upper}\` for a non-ASCII character.
pub(super) fn is_upper(c: char) -> bool {
    contains(UPPERS, c)
}

/// The regex \`\\d\` for a non-ASCII character.
pub(super) fn is_digit(c: char) -> bool {
    contains(DIGITS, c)
}
`;
await Bun.write(`${root}src/python/classes.rs`, out);
console.log(ranges(words).length, ranges(starts).length, ranges(spaces).length, ranges(uppers).length, ranges(digits).length);
