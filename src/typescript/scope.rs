//! The scope names the lexer emits, in Shiki's naming.
//!
//! The `typescript`, `javascript`, `jsx` and `tsx` grammars differ only in the
//! suffix of their names.
//! One table therefore holds the four spellings one after another.
//! A scope's number is its index plus a whole table's length for each dialect
//! before its own.

use super::Dialect;

macro_rules! scopes {
    ($($id:ident $ts:literal $js:literal $jsx:literal $tsx:literal)*) => {
        /// A scope name.
        /// The discriminant indexes the table of each dialect.
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        #[repr(u16)]
        pub(crate) enum S { $($id),* }

        /// The number of scope names a dialect has.
        #[expect(
            clippy::as_conversions,
            clippy::cast_possible_truncation,
            reason = "`u16::try_from` is not const; the table has a few hundred names"
        )]
        const COUNT: u16 = [$($ts),*].len() as u16;

        impl S {
            /// The scope in `dialect`'s spelling, in the crate's shared
            /// numbering.
            #[expect(
                clippy::as_conversions,
                reason = "a fieldless `repr(u16)` enum has no `From` impl for its discriminant"
            )]
            pub(crate) const fn scope(self, dialect: Dialect) -> crate::scope::Scope {
                crate::scope::Scope::new(
                    crate::scope::TYPESCRIPT,
                    self as u16 + COUNT * dialect.index(),
                )
            }
        }

        /// The name of every scope of every dialect: `typescript`, then
        /// `javascript`, then `jsx`, then `tsx`.
        pub(crate) const NAMES: &[&str] = &[
            $($ts,)*
            $($js,)*
            $($jsx,)*
            $($tsx,)*
        ];
    };
}

